/**
 * Офлайн-руководство по Genshin Impact.
 *
 * Весь контент лежит здесь, в одном файле: чтобы обновить гайд после выхода новой версии,
 * достаточно поправить [GAME_VERSION], [DATA_DATE] и нужные карточки в [GenshinGuide.cards].
 */

sealed interface GuideBlock {
    /** Обычный абзац. */
    data class Para(val text: String) : GuideBlock

    /** Подзаголовок внутри карточки. */
    data class Sub(val text: String) : GuideBlock

    /** Маркированный список. */
    data class Bullets(val items: List<String>) : GuideBlock

    /** Плашка-примечание; [warning] — для предупреждений и спорных/непроверенных данных. */
    data class Note(val text: String, val warning: Boolean = false) : GuideBlock

    /** Таблица; [weights] — относительная ширина столбцов (по умолчанию поровну). */
    data class Table(
        val header: List<String>,
        val rows: List<List<String>>,
        val weights: List<Float> = emptyList(),
    ) : GuideBlock
}

data class GuideCard(
    val title: String,
    val subtitle: String = "",
    val tag: String = "",
    val blocks: List<GuideBlock>,
    val expandedByDefault: Boolean = true,
) {
    /** Плоский текст карточки для поиска. */
    fun searchText(): String = buildString {
        append(title).append(' ').append(subtitle).append(' ').append(tag).append(' ')
        blocks.forEach { b ->
            when (b) {
                is GuideBlock.Para -> append(b.text)
                is GuideBlock.Sub -> append(b.text)
                is GuideBlock.Bullets -> append(b.items.joinToString(" "))
                is GuideBlock.Note -> append(b.text)
                is GuideBlock.Table -> {
                    append(b.header.joinToString(" "))
                    append(' ')
                    append(b.rows.joinToString(" ") { it.joinToString(" ") })
                }
            }
            append(' ')
        }
    }
}

enum class GuideSection(val title: String) {
    REACTIONS("Реакции"),
    LUNAR("Лунные"),
    STELLAR("Звёздные"),
    RESONANCE("Резонанс"),
    BUILD("Статы и билды"),
    WISHES("Молитвы"),
    RESET("Смола и сбросы"),
    TIPS("Советы"),
}

