    fun cards(section: GuideSection): List<GuideCard> = when (section) {
        GuideSection.REACTIONS -> reactions
        GuideSection.LUNAR -> lunar
        GuideSection.STELLAR -> stellar
        GuideSection.RESONANCE -> resonance
        GuideSection.BUILD -> build
        GuideSection.WISHES -> wishes()
        GuideSection.RESET -> reset
        GuideSection.TIPS -> tips
    }

    fun search(query: String): List<GuideCard> {
        val q = query.trim()
        if (q.isEmpty()) return emptyList()
        return GuideSection.entries
            .flatMap { cards(it) }
            .filter { it.searchText().contains(q, ignoreCase = true) }
    }

